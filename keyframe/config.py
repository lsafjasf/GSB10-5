"""检测阈值配置。所有阈值都有注释说明物理含义，便于按视频类型调整。"""


class Config:
    # ---- 硬切换 ----
    CUT_CHI2 = 0.45        # 直方图卡方 > 此值：内容被整体替换
    CUT_FRAC = 0.80        # 且空间变化比例 > 此值（排除同分布的亮度跳变）

    # ---- 闪光灯（瞬时亮度突变，非切换）----
    FLASH_DMEAN = 30.0     # |平均亮度差| 超过此值且 chi2 中高 -> 闪光灯

    # ---- 渐变转场 ----
    GRAD_FRAC_LOW = 0.20   # 空间变化比例下限（低于它是静态）
    GRAD_CHI2_LOW = 0.015   # 直方图变化下限（淡入淡出时 chi2 很小）
    GRAD_DMEAN_STEP = 1.5  # 每帧亮度漂移超过此值也算渐变迹象（淡入淡出）
    GRAD_MIN_FRAMES = 5    # 至少持续这么多帧才确认是渐变
    GRAD_MAX_DMEAN = 8.0   # 累计亮度漂移达到此值可确认（淡入淡出）
    GRAD_CHI2_MIN = 0.08   # 或段内最大 chi2 达到此值可确认（溶解）

    # ---- 快速运动（不产关键帧，仅区分用）----
    MOTION_FRAC = 0.35     # 空间变化比例高
    MOTION_CHI2 = 0.20     # 但直方图变化低（内容没变，只是位置变了）

    # ---- 段统计 ----
    SEG_MIN_FRAMES = 3     # 运动/静态段最短帧数（评估用）
    MID_CHI2 = 0.20        # 闪光灯判定时参考的“中高 chi2”
    MID_FRAC = 0.35
