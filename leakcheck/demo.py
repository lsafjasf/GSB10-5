"""改写样例命中演示：改字 / 换序 / 拆散拼接 / 无关。"""
from leakfp import LeakIndex, tokenize

ORIGINAL = (
    "本公司核心技术白皮书规定，所有用户数据在传输过程中必须采用国密算法加密，"
    "存储时按照密级分别落盘，密钥由独立的密钥管理系统统一轮换，"
    "任何员工不得以任何形式将明文数据带离受控网络环境，"
    "违者将依据保密协议追究法律责任并解除劳动合同。"
)

VARIANTS = {
    "改字版": ORIGINAL.replace("国密算法", "商用密码算法")
                     .replace("统一轮换", "定期轮换")
                     .replace("解除劳动合同", "解除劳动关系"),
    "换序版": "。".join([p for p in ORIGINAL.split("。") if p][::-1]) + "。",
    "拆散拼接版": (
        "近日某行业论坛上出现一篇帖子，开头聊的是天气和股价。"
        "所有用户数据在传输过程中必须采用国密算法加密，存储时按照密级分别落盘，"
        "随后帖子又插入大段与主题无关的广告内容，"
        "任何员工不得以任何形式将明文数据带离受控网络环境，违者将依据保密协议追究法律责任。"
        "帖子结尾则是一些表情包和闲聊。"
    ),
    "无关版": (
        "今天的发布会介绍了新款手机的摄像头参数，主摄采用一英寸传感器，"
        "支持光学防抖和夜景模式，电池容量也有所提升，起售价保持不变。"
    ),
}

idx = LeakIndex()
idx.add("whitepaper-v3", ORIGINAL)

print(f"{'样例':<10}{'命中':<6}{'共同指纹数':>10}{'查询包含率':>12}{'源覆盖率':>10}")
print("-" * 52)
for name, text in VARIANTS.items():
    hits = idx.query(text)
    if hits:
        h = hits[0]
        print(f"{name:<10}{'是':<8}{h['matched']:>8}"
              f"{h['query_containment']*100:>11.1f}%{h['source_coverage']*100:>9.1f}%")
    else:
        print(f"{name:<10}{'否':<8}{'-':>8}{'-':>12}{'-':>10}")
