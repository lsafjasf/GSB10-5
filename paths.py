"""输出典型情形的插值路径数据（t = 0, 0.1, ..., 1.0）。"""

from slerp import slerp_path, central_angle
import math

CASES = [
    ("同半球短弧 (35,120)->(40,130)", (35.0, 120.0), (40.0, 130.0)),
    ("跨经度分界 (10,170)->(10,-170)", (10.0, 170.0), (10.0, -170.0)),
    ("跨分界+跨赤道 (-20,179.9)->(30,-179.9)", (-20.0, 179.9), (30.0, -179.9)),
    ("极点附近 (89,0)->(89,180)", (89.0, 0.0), (89.0, 180.0)),
    ("起点即极点 (90,0)->(0,180)", (90.0, 0.0), (0.0, 180.0)),
    ("对跖点 (10,30)->(-10,-150)", (10.0, 30.0), (-10.0, -150.0)),
    ("两点重合 (25,60)->(25,60)", (25.0, 60.0), (25.0, 60.0)),
]

for name, p1, p2 in CASES:
    sigma = math.degrees(central_angle(*p1, *p2))
    print(f"\n== {name}  圆心角={sigma:.6f}° ==")
    print(f"{'t':>5} {'lat':>12} {'lon':>13}")
    for i, (lat, lon) in enumerate(slerp_path(*p1, *p2, 10)):
        print(f"{i/10:>5.1f} {lat:>12.6f} {lon:>13.6f}")
