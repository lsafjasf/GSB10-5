"""Deterministic synthetic history generator.

The repository ships no production data, so the labelled "history" used to
fit weights is generated by a fully specified, seeded process.  Latent
normalized factor values x_j ~ U(0,1) are drawn first; rollback labels come
from sigmoid(TRUE_INTERCEPT + TRUE_WEIGHTS . x + noise); raw change metrics
are then inverted from x so that the library's own factor functions +
empirical-percentile normalization recover (approximately) x.  The fitting
pipeline must recover TRUE_WEIGHTS from the labels alone -- this is itself
one of the self-tests.  In production you would swap ``generate_history``
for a loader over your real change/rollback log; every downstream step
(fit, decompose, sensitivity, validation) is identical.
"""
from __future__ import annotations

import math
import random
from typing import List, Sequence, Tuple

from .factors import (ChangeMetrics, FileInfo, fit_ecdf, normalize_vector,
                      raw_factor_vector)

# Latent "true" weights of the generator (sum to 1), ordered as FACTORS:
# size, hotness, test_gap, author_inexperience, author_rollback_rate,
# review_gap, schedule_pressure
TRUE_WEIGHTS: Tuple[float, ...] = (0.20, 0.10, 0.20, 0.10, 0.15, 0.15, 0.10)
# Logistic coefficients of the generator.  Their *ratios* are TRUE_WEIGHTS;
# their magnitude (sum = 8) sets how strongly the factors move rollback
# probability across the population (p ranges roughly 0.2% .. 97%).
TRUE_BETA: Tuple[float, ...] = tuple(16.0 * w for w in TRUE_WEIGHTS)
TRUE_INTERCEPT = -11.0          # tuned so the base rollback rate is ~10%
NOISE_STD = 0.08               # unobserved factors (kept small: signal >> noise)


def _invert_to_metrics(x: Sequence[float], rng: random.Random) -> ChangeMetrics:
    """Invert normalized factor values back into plausible raw metrics."""
    size, hot, tgap, inexp, rb_rate, rgap, sched = x
    churn = max(0, int(round(math.expm1(size * math.log1p(10_000)))))
    la = int(churn * rng.uniform(0.5, 0.8))
    ld = churn - la
    n_files = 1 + rng.randrange(3)
    files = tuple(
        FileInfo(
            path=f"src/mod{rng.randrange(40)}/f{rng.randrange(200)}.py",
            churn_90d=int(round(20.0 * hot)),
            test_ratio=1.0 - tgap,
            ownership_frac=min(1.0, rng.betavariate(2.0, 3.0)),
        )
        for _ in range(n_files)
    )
    prior = int(round((1.0 - inexp) / max(inexp, 1e-9)))
    prior = min(prior, 500)
    rollbacks = int(round(rb_rate * prior)) if prior > 0 else 0
    if rgap >= 0.999:
        reviewers, comments = 0, 0
    else:
        reviewers = rng.choice((1, 2, 3))
        breadth = min(1.0, reviewers / 3.0)
        depth = max(0.0, min(0.999, (1.0 - rgap) / breadth))
        comments = int(round(-5.0 * math.log(1.0 - depth)))
    return ChangeMetrics(
        lines_added=la,
        lines_deleted=ld,
        files=files,
        author_prior_changes=prior,
        author_prior_rollbacks=rollbacks,
        reviewer_count=reviewers,
        review_comment_count=comments,
        is_emergency=sched >= 0.6 - 1e-9,
        is_off_hours=not (sched < 0.3 - 1e-9),
        is_release_window=sched >= 0.9 - 1e-9,
    )


def generate_history(n: int, seed: int = 42
                     ) -> Tuple[List[ChangeMetrics], List[List[float]], List[int],
                                List[List[float]]]:
    """Return (metrics, normalized vectors, rollback labels, ecdf)."""
    rng = random.Random(seed)
    noise_rng = random.Random(seed + 1)
    k = len(TRUE_WEIGHTS)
    latents = [[rng.random() for _ in range(k)] for _ in range(n)]
    y: List[int] = []
    for x in latents:
        z = TRUE_INTERCEPT + sum(b * v for b, v in zip(TRUE_BETA, x))
        z += noise_rng.gauss(0.0, NOISE_STD)
        p = 1.0 / (1.0 + math.exp(-z))
        y.append(1 if rng.random() < p else 0)
    metrics = [_invert_to_metrics(x, rng) for x in latents]
    raws = [raw_factor_vector(m) for m in metrics]
    ecdf = fit_ecdf(raws)
    X = [normalize_vector(r, ecdf) for r in raws]
    return metrics, X, y, ecdf
